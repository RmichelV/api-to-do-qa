#!/bin/bash
set -e

: "${MARIADB_ROOT_PASSWORD:?}"
: "${DB_NAME:?}"
: "${DB_USER:?}"
: "${DB_PASSWORD:?}"
: "${MIGRATE_DB_USER:?}"
: "${MIGRATE_DB_PASSWORD:?}"

mariadb --protocol=socket --user=root --password="$MARIADB_ROOT_PASSWORD" <<SQL
CREATE DATABASE IF NOT EXISTS ${DB_NAME} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER '${DB_USER}'@'%' IDENTIFIED BY '${DB_PASSWORD}';
GRANT SELECT, INSERT, UPDATE, DELETE ON ${DB_NAME}.* TO '${DB_USER}'@'%';
CREATE USER '${MIGRATE_DB_USER}'@'%' IDENTIFIED BY '${MIGRATE_DB_PASSWORD}';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, INDEX, REFERENCES ON ${DB_NAME}.* TO '${MIGRATE_DB_USER}'@'%';
FLUSH PRIVILEGES;
SQL